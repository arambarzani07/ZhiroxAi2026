package main

import (
    "crypto/ed25519"
    "encoding/base64"
    "encoding/hex"
    "fmt"
    "os"
    "path/filepath"
    "strings"
)

func main() {
    seedB64 := strings.TrimSpace(os.Getenv("ZHIROX_UPDATE_ED25519_SEED_B64"))
    if seedB64 == "" {
        fatal("ZHIROX_UPDATE_ED25519_SEED_B64 is required; trust preparation is fail-closed")
    }
    seed, err := base64.StdEncoding.DecodeString(seedB64)
    if err != nil || len(seed) != ed25519.SeedSize {
        fatal("release signing seed must be base64-encoded 32-byte Ed25519 seed")
    }

    privateKey := ed25519.NewKeyFromSeed(seed)
    publicKey := privateKey.Public().(ed25519.PublicKey)
    publicHex := hex.EncodeToString(publicKey)

    if err := os.MkdirAll("buildsrc", 0755); err != nil {
        fatal(err.Error())
    }
    if err := os.MkdirAll("channel", 0755); err != nil {
        fatal(err.Error())
    }

    source := "package main\n\n// Generated by the release workflow from the signing key's public half.\nconst pcOSPinnedUpdatePublicKeyHex = \"" + publicHex + "\"\n"
    if err := os.WriteFile(filepath.Clean("buildsrc/update_trust_v510.go"), []byte(source), 0600); err != nil {
        fatal(err.Error())
    }
    if err := os.WriteFile(filepath.Clean("channel/update-public-key.hex"), []byte(publicHex+"\n"), 0644); err != nil {
        fatal(err.Error())
    }

    fmt.Println("prepared pinned Ed25519 release trust anchor", publicHex[:16]+"...")
}

func fatal(msg string) {
    fmt.Fprintln(os.Stderr, msg)
    os.Exit(1)
}
